/**
 * Builds lib/templates/icon-catalog.ts from lucide-react's icon node data so the same
 * paths render in the editor (SVG) and in the PDF (react-pdf Svg).
 *
 * Run: node scripts/generate-icon-catalog.mjs
 */
import { writeFile } from "node:fs/promises"
import { pathToFileURL } from "node:url"
import path from "node:path"

const ICON_NAMES = [
  // Achievement & events
  "award", "medal", "trophy", "crown", "sparkles", "star", "badge-check", "graduation-cap", "ticket",
  "party-popper", "gift", "cake", "calendar", "clock", "map-pin", "flag", "bookmark",
  // People & business
  "user", "users", "building-2", "briefcase", "handshake", "id-card", "signature", "stamp",
  "scale", "landmark", "store", "factory", "truck", "package", "shopping-bag", "shopping-cart",
  "credit-card", "banknote", "receipt", "percent", "tag", "tags", "qr-code", "barcode", "scan-line",
  // Communication
  "mail", "phone", "globe", "link", "at-sign", "message-circle", "send", "hash", "share-2",
  "smartphone", "laptop", "monitor", "printer", "wifi",
  // Status & arrows
  "check", "circle-check", "circle-x", "x", "plus", "minus", "info", "triangle-alert", "shield-check",
  "lock", "key", "arrow-right", "arrow-left", "arrow-up-right", "chevron-right", "quote",
  // Lifestyle
  "heart", "thumbs-up", "coffee", "utensils", "pizza", "wine", "leaf", "flower-2", "tree-pine",
  "sun", "moon", "cloud", "droplet", "flame", "zap", "lightbulb", "rocket", "plane", "car", "bike",
  "ship", "anchor", "mountain", "camera", "image", "music", "film", "book-open", "pen-line",
  "pencil", "scissors", "wrench", "settings", "stethoscope", "pill", "dumbbell", "house", "bell",
  "headphones", "mic", "video", "paw-print", "dog", "cat", "fish",
]

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..")
const iconsDir = path.join(root, "node_modules", "lucide-react", "dist", "esm", "icons")

const entries = []
const missing = []

for (const name of ICON_NAMES) {
  try {
    const mod = await import(pathToFileURL(path.join(iconsDir, `${name}.mjs`)).href)
    const node = mod.__iconNode

    if (!Array.isArray(node)) {
      missing.push(name)
      continue
    }

    const cleaned = node.map(([tag, attrs]) => {
      const rest = { ...attrs }
      delete rest.key
      return [tag, rest]
    })

    entries.push([name, cleaned])
  } catch {
    missing.push(name)
  }
}

const lines = entries.map(
  ([name, node]) => `  ${JSON.stringify(name)}: ${JSON.stringify(node)},`
)

const output = `// Generated by scripts/generate-icon-catalog.mjs from lucide-react (ISC). Do not edit by hand.

export type IconNodeAttributes = Record<string, string | number>
export type IconNode = Array<[string, IconNodeAttributes]>

export const iconCatalog: Record<string, IconNode> = {
${lines.join("\n")}
}

export const iconNames = Object.keys(iconCatalog)
`

await writeFile(path.join(root, "lib", "templates", "icon-catalog.ts"), output)

console.log(`Wrote ${entries.length} icons`)

if (missing.length > 0) {
  console.log(`Missing: ${missing.join(", ")}`)
}
